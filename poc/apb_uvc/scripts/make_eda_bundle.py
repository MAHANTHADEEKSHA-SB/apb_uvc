"""Concatenate a filelist into one SystemVerilog file for EDA Playground.

EDA Playground compiles files placed in its editor panes rather than
filelists, so this expands a .f file (nested -F/-f, paths relative to each
filelist, +incdir+ directories, // comments) into a single file in compile
order. `include directives that resolve to a file in an +incdir+ directory
are inlined, so the bundle needs no include path; includes that do not
resolve (for example "uvm_macros.svh", supplied by the simulator's UVM
library) are left untouched. Paste the result into the testbench pane and
select the top module(s).

This is plain text processing; it does not run any simulator or compiler.

Usage: python3 -I make_eda_bundle.py <filelist.f> <output.sv> [+define+NAME[=VALUE] ...]
"""
import os
import re
import sys

INCLUDE_RE = re.compile(r'^\s*`include\s+"([^"]+)"')


def expand(filelist, sources, incdirs, seen):
    """Append source paths and include directories from filelist, in order."""
    base = os.path.dirname(os.path.abspath(filelist))
    with open(filelist, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.split("//", 1)[0].strip()
            if not line:
                continue
            if line.startswith(("-F ", "-f ")):
                nested = os.path.normpath(os.path.join(base, line[3:].strip()))
                expand(nested, sources, incdirs, seen)
                continue
            if line.startswith("+incdir+"):
                for directory in line[len("+incdir+"):].split("+"):
                    if directory:
                        incdirs.append(os.path.normpath(os.path.join(base, directory)))
                continue
            if line.startswith(("-", "+")):
                raise SystemExit(f"unsupported filelist option in {filelist}: {line}")
            path = os.path.normpath(os.path.join(base, line))
            if path not in seen:
                seen.add(path)
                sources.append(path)


def find_include(name, including_file, incdirs):
    """Resolve an `include name like a simulator: own directory, then +incdir+."""
    for directory in [os.path.dirname(including_file)] + incdirs:
        candidate = os.path.join(directory, name)
        if os.path.isfile(candidate):
            return os.path.normpath(candidate)
    return None


def emit(path, out, incdirs, root, stack):
    """Write path to out, inlining resolvable `include files recursively."""
    if path in stack:
        raise SystemExit(f"recursive `include of {path}")
    with open(path, encoding="utf-8") as src:
        for line in src:
            match = INCLUDE_RE.match(line)
            target = find_include(match.group(1), path, incdirs) if match else None
            if target is None:
                out.write(line)
                continue
            out.write(f"// ---- begin `include \"{match.group(1)}\" ({os.path.relpath(target, root)})\n")
            emit(target, out, incdirs, root, stack + [path])
            out.write(f"// ---- end `include \"{match.group(1)}\"\n")


def main(argv):
    if len(argv) < 2:
        raise SystemExit(__doc__)
    filelist, output, defines = argv[0], argv[1], argv[2:]
    sources, incdirs = [], []
    expand(filelist, sources, incdirs, set())
    root = os.path.dirname(os.path.dirname(os.path.abspath(filelist)))
    with open(output, "w", encoding="utf-8") as out:
        out.write(f"// Generated by make_eda_bundle.py from {os.path.relpath(filelist, root)}\n")
        out.write("// Do not edit: regenerate from the source files.\n")
        for define in defines:
            if not define.startswith("+define+"):
                raise SystemExit(f"expected +define+NAME, got {define}")
            out.write(f"`define {define[len('+define+'):].replace('=', ' ', 1)}\n")
        for path in sources:
            out.write(f"\n// ==== {os.path.relpath(path, root)} ====\n")
            emit(path, out, incdirs, root, [])
    print(f"wrote {output}: {len(sources)} files, {len(incdirs)} include directories")


if __name__ == "__main__":
    main(sys.argv[1:])
