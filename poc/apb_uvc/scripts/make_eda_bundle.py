"""Concatenate a filelist into one SystemVerilog file for EDA Playground.

EDA Playground compiles files placed in its editor panes rather than
filelists, so this expands a .f file (nested -F/-f, paths relative to each
filelist, // comments) into a single file in compile order. Paste the
result into the testbench pane and select the top module.

Usage: python3 -I make_eda_bundle.py <filelist.f> <output.sv> [+define+NAME ...]
"""
import os
import sys


def expand(filelist, seen):
    """Return source paths from filelist in order, following -F/-f."""
    base = os.path.dirname(os.path.abspath(filelist))
    sources = []
    with open(filelist, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.split("//", 1)[0].strip()
            if not line:
                continue
            if line.startswith(("-F ", "-f ")):
                nested = os.path.normpath(os.path.join(base, line[3:].strip()))
                sources += expand(nested, seen)
                continue
            if line.startswith(("-", "+")):
                raise SystemExit(f"unsupported filelist option in {filelist}: {line}")
            path = os.path.normpath(os.path.join(base, line))
            if path not in seen:
                seen.add(path)
                sources.append(path)
    return sources


def main(argv):
    if len(argv) < 2:
        raise SystemExit(__doc__)
    filelist, output, defines = argv[0], argv[1], argv[2:]
    sources = expand(filelist, set())
    root = os.path.dirname(os.path.dirname(os.path.abspath(filelist)))
    with open(output, "w", encoding="utf-8") as out:
        out.write(f"// Generated by make_eda_bundle.py from {os.path.relpath(filelist, root)}\n")
        out.write("// Do not edit: regenerate from the source files.\n")
        for define in defines:
            if not define.startswith("+define+"):
                raise SystemExit(f"expected +define+NAME, got {define}")
            out.write(f"`define {define[len('+define+'):].replace('=', ' ', 1)}\n")
        for path in sources:
            out.write(f"\n// ==== {os.path.relpath(path, root)} ====\n")
            with open(path, encoding="utf-8") as src:
                out.write(src.read())
    print(f"wrote {output}: {len(sources)} files")


if __name__ == "__main__":
    main(sys.argv[1:])
